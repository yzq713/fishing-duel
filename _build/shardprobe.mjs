const info = await page.evaluate(() => {
  const T = window.THREE;
  const cam = window.game.world.scene ? null : null;
  const camera = window.game.player.camera || (window.game.camera);
  const rc = new T.Raycaster();
  rc.setFromCamera(new T.Vector2(0.28, 0.15), camera);
  const scene = window.game.scene;
  const hits = rc.intersectObjects(scene.children, true).slice(0, 6);
  const parts = [];
  scene.traverse(o => { if (o.isMesh) parts.push((o.material && o.material.name) || (o.material && o.material.type) || '?'); });
  return { hits: hits.map(h => ({ d: +h.distance.toFixed(2), p: [h.point.x, h.point.y, h.point.z].map(n => +n.toFixed(2)), mat: h.object.material && (h.object.material.name || h.object.material.type), geo: h.object.geometry.type })) };
});
console.log(JSON.stringify(info));
