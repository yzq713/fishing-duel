const hits = await page.evaluate(() => {
  const T = window.THREE, scene = window.game.scene;
  const cam = window.game.player.camera || window.game.camera;
  const rc = new T.Raycaster();
  const pts = [[0.04, 0.70], [-0.02, 0.72], [0.10, 0.40], [0.02, 0.44], [0.0, 0.30]];
  const out = [];
  pts.forEach(([x, y]) => {
    rc.setFromCamera(new T.Vector2(x, y), cam);
    const h = rc.intersectObjects(scene.children, true).filter(i => i.object.isMesh).slice(0, 2);
    out.push({ ndc: [x, y], hits: h.map(i => ({ n: i.object.name, chain: (() => { let s = [], o = i.object; while (o && s.length < 5) { s.push(o.name || o.type); o = o.parent; } return s.join('<'); })(), d: +i.distance.toFixed(1) })) });
  });
  return out;
});
