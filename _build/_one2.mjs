import puppeteer from 'puppeteer-core';
const NAME = process.argv[2] || '血月鳗';
const b = await puppeteer.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: 'new', args: ['--no-sandbox','--use-angle=d3d11','--enable-unsafe-swiftshader','--allow-file-access-from-files','--window-size=1200,800'] });
const p = await b.newPage();
await p.setViewport({ width: 1200, height: 800 });
const logs=[];
p.on('pageerror',e=>logs.push('ERR '+String(e).slice(0,300)));
p.on('console',m=>{ if(m.type()==='error'||m.type()==='warning') logs.push(m.type()+' '+m.text().slice(0,300)); });
await p.goto('file:///C:/Users/ASUS/Documents/Trae-CN/temp_20261108_01/fishing-duel/index.html?v='+Date.now(),{waitUntil:'load',timeout:120000});
await p.waitForFunction('window.game && window.game.world',{timeout:90000});
await new Promise(r=>setTimeout(r,2400));
await p.evaluate(()=>document.getElementById('soloBtn').click());
await new Promise(r=>setTimeout(r,400));
await p.evaluate(()=>document.getElementById('charNextBtn').click());
await new Promise(r=>setTimeout(r,300));
await p.evaluate(()=>document.getElementById('fightBtn').click());
await new Promise(r=>setTimeout(r,2000));
const before = await p.evaluate(()=>({f:window.game.renderer.info.render.frame, gl: window.game.renderer.getContext().isContextLost()}));
const info = await p.evaluate((name)=>{
  const g=window.game; g.state='playing';
  g.player.noGravity=true; g.player.pos.set(0,30,0); g.player.yaw=0; g.player.pitch=0;
  g.scene.traverse(o=>{if(o.isMesh||o.isSprite||o.isPoints)o.visible=false;});
  g.scene.background=new THREE.Color(0x0b0407); g.scene.fog=null;
  const m=new window.FishModel(name);
  g.scene.add(m.group);
  m.group.traverse(o=>{if(o.isMesh||o.isSprite||o.isPoints)o.visible=true;});
  const cam=g.camera; cam.updateMatrixWorld(true);
  const dir=new THREE.Vector3(); cam.getWorldDirection(dir);
  m.group.position.copy(cam.position.clone().addScaledVector(dir,3.0));
  m.group.updateMatrixWorld(true);
  const box=new THREE.Box3().setFromObject(m.group); const sz=new THREE.Vector3(); box.getSize(sz);
  const maxDim=Math.max(sz.x,sz.y,sz.z)||1;
  m.group.scale.setScalar(2.2/maxDim);
  // 检查顶点里的 NaN
  let nan=0, meshes=0;
  m.group.traverse(o=>{ if(o.isMesh&&o.geometry&&o.geometry.attributes.position){ meshes++;
    const a=o.geometry.attributes.position.array; for(let i=0;i<a.length;i++){ if(!isFinite(a[i])) { nan++; break; } } }});
  window._m=m;
  return {maxDim:+maxDim.toFixed(2), meshes, nanMeshes:nan};
}, NAME);
await new Promise(r=>setTimeout(r,1200));
const after = await p.evaluate(()=>({f:window.game.renderer.info.render.frame, gl: window.game.renderer.getContext().isContextLost(), calls: window.game.renderer.info.render.calls, tris: window.game.renderer.info.render.triangles}));
await p.screenshot({path:`D:/下载/fishprobe/tiles/_one2_${NAME}.png`});
console.log(JSON.stringify({before,info,after}),'\nlogs', logs.slice(0,6).join('\n'));
await b.close();
